/// ESC/POS for the emergency KOT slip: a faithful Dart mirror of the desk's
/// `buildKotEscpos` + `toPrinterSafeText` (command.desk
/// `src/app/core/print/kot-escpos.ts`) and of the byte layout in
/// `electron/printer/escpos.ts` (`buildDoc` / `sendNetworkPrint`).
///
/// It is a PURE function of its input (no IO, no Flutter) so the bytes can be
/// pinned by a golden test, and so a slip printed from the phone looks exactly
/// like the desk's own. Keep any change here in step with the desk file.
///
/// Wire format, as the desk sends it: one string, encoded latin1, one copy after
/// another (every copy re-inits the printer) — anything above ASCII has already
/// been transliterated or replaced with `?` because printers ship in code page
/// 437/850 and would print the wrong glyph.
library;

import 'dart:convert';

const String _esc = '\x1B';
const String _gs = '\x1D';
const String _init = '$_esc@';
const String _alignLeft = '$_esc' 'a\x00';
const String _alignCenter = '$_esc' 'a\x01';
const String _boldOn = '$_esc' 'E\x01';
const String _boldOff = '$_esc' 'E\x00';
const String _sizeDouble = '$_gs!\x11';
const String _sizeNormal = '$_gs!\x00';
const String _feed3 = '\n\n\n';

/// `GS V 66 0`: feed to the cut position, partial cut.
const String _cutPartial = '$_gs' 'V\x42\x00';
const String _rule = '------------------------------\n';

/// The printed sections of one ticket (the desk's `EscposDoc`).
class EscposDoc {
  final String title;
  final List<String> subtitleLines;
  final List<String> itemLines;
  final List<String> footerLines;

  const EscposDoc({
    required this.title,
    this.subtitleLines = const <String>[],
    this.itemLines = const <String>[],
    this.footerLines = const <String>[],
  });
}

/// One item line on the slip (the desk's `KotItemView`, already decoded).
class KotSlipItem {
  final String name;
  final int quantity;
  final String? variationName;

  /// Selected option names, joined with ", " on the slip.
  final List<String> options;

  /// Add-on groups: group name -> choice names. Joined `Group: a, b | Group2: c`.
  final List<({String group, List<String> choices})> addons;
  final String? notes;

  /// A weighed item prints its weight instead of "N x".
  final double? weight;
  final String? weightUnit;

  const KotSlipItem({
    required this.name,
    required this.quantity,
    this.variationName,
    this.options = const <String>[],
    this.addons = const <({String group, List<String> choices})>[],
    this.notes,
    this.weight,
    this.weightUnit,
  });
}

/// Everything the slip prints (the desk's `KotEscposContext`).
class KotSlipContext {
  final String stationLabel;

  /// For the offline slip this is the `offline_ref` (e.g. `A7Q2-014`), printed
  /// where the desk prints its KOT number.
  final String kotNumber;

  /// Null/empty when the order has no number yet (offline orders are created
  /// only when the outbox replays) — the "Order:" line is then left out.
  final String? orderNumber;
  final String tableName;
  final String? floorName;

  /// The word before the table name. Defaults to "Table".
  final String slotLabel;

  /// Drop the slot label and print the bare table name.
  final bool nameOnly;
  final String? guestName;
  final String? waiterName;
  final String? operatorName;
  final String? orderNotes;
  final String dateStr;
  final String timeStr;
  final bool isReprint;

  /// Adds the `*** OFFLINE KOT ***` banner (printed where a reprint's banner
  /// goes) so the kitchen knows this slip came from a handset, not the desk.
  final bool isOffline;
  final List<KotSlipItem> items;

  const KotSlipContext({
    required this.stationLabel,
    required this.kotNumber,
    this.orderNumber,
    required this.tableName,
    this.floorName,
    this.slotLabel = 'Table',
    this.nameOnly = false,
    this.guestName,
    this.waiterName,
    this.operatorName,
    this.orderNotes,
    required this.dateStr,
    required this.timeStr,
    this.isReprint = false,
    this.isOffline = false,
    required this.items,
  });
}

bool _has(String? v) => v != null && v.trim().isNotEmpty;

final RegExp _combiningMarks = RegExp('[̀-ͯ]');
final RegExp _whitespaceControls = RegExp(r'[\t\r\n]+');
final RegExp _nonPrintableAscii = RegExp(r'[^\x20-\x7E]');

/// Applied in this order, before normalisation — the desk's `TRANSLITERATIONS`.
final List<(RegExp, String)> _transliterations = <(RegExp, String)>[
  (RegExp('₹'), 'Rs'),
  (RegExp('[‘’‚′]'), "'"),
  (RegExp('[“”„″]'), '"'),
  (RegExp('[–—−]'), '-'),
  (RegExp('…'), '...'),
  (RegExp('[•·●]'), '*'),
  (RegExp('×'), 'x'),
  (RegExp(' '), ' '),
  (RegExp('½'), '1/2'),
  (RegExp('¼'), '1/4'),
  (RegExp('¾'), '3/4'),
  (RegExp('[Ææ]'), 'ae'),
  (RegExp('ß'), 'ss'),
  (RegExp('[Øø]'), 'o'),
  (RegExp('[Ðð]'), 'd'),
];

/// Printers ship in code page 437/850 and the transport is latin1, so anything
/// above ASCII prints as the wrong glyph. Only printable ASCII is guaranteed to
/// print as written, so everything else is transliterated or replaced with `?`.
///
/// Mirrors the desk's `toPrinterSafeText`, including its `normalize('NFKD')` +
/// combining-mark strip (so `e-acute` prints as `e`). Dart's core has no Unicode
/// normaliser, so NFKD is table-driven ([_nfkdStripped], generated from the
/// Unicode data for Latin, Indic and compatibility forms); a character outside
/// the table is not decomposable and becomes `?`, exactly as on the desk.
String toPrinterSafeText(String text) {
  var out = text;
  for (final (pattern, replacement) in _transliterations) {
    out = out.replaceAll(pattern, replacement);
  }
  final buffer = StringBuffer();
  for (final rune in out.runes) {
    final mapped = _nfkdStripped[rune];
    buffer.write(mapped ?? String.fromCharCode(rune));
  }
  out = buffer.toString().replaceAll(_combiningMarks, '');
  out = out.replaceAll(_whitespaceControls, ' ');
  return out.replaceAll(_nonPrintableAscii, '?');
}

String _optionsText(List<String> options) =>
    options.where((o) => o.isNotEmpty).join(', ');

String _addonsText(List<({String group, List<String> choices})> addons) =>
    addons
        .where((g) => g.choices.isNotEmpty)
        .map((g) => '${g.group}: ${g.choices.join(', ')}')
        .join(' | ');

const String _indent = '    ';

String _weightText(double weight) {
  // JS prints a whole-number double without ".0" (`1` not `1.0`).
  if (weight == weight.truncateToDouble()) return weight.toInt().toString();
  return weight.toString();
}

List<String> _itemLines(KotSlipItem it) {
  final variation = _has(it.variationName) ? ' (${it.variationName})' : '';
  final lead = it.weight != null
      ? '${_weightText(it.weight!)}${it.weightUnit ?? ''}'
      : '${it.quantity} x';
  final lines = <String>['$lead ${it.name}$variation'];
  final options = _optionsText(it.options);
  if (options.isNotEmpty) lines.add('$_indent$options');
  final addons = _addonsText(it.addons);
  if (addons.isNotEmpty) lines.add('$_indent$addons');
  if (_has(it.notes)) lines.add('$_indent! ${it.notes}');
  return lines;
}

/// The desk's `buildKotEscpos`.
EscposDoc buildKotEscpos(KotSlipContext ctx) {
  final slotLabel = _has(ctx.slotLabel) ? ctx.slotLabel : 'Table';
  final where = '${ctx.nameOnly ? '' : '$slotLabel '}${ctx.tableName}'.trim();
  final whereLine = _has(ctx.floorName) ? '${ctx.floorName} | $where' : where;

  final subtitleLines = <String>[
    if (ctx.isOffline) '*** OFFLINE KOT ***',
    if (ctx.isReprint) '*** REPRINT ***',
    'KOT: ${ctx.kotNumber}',
    if (_has(ctx.orderNumber)) 'Order: ${ctx.orderNumber}',
    whereLine,
    if (_has(ctx.guestName)) 'Guest: ${ctx.guestName}',
    '${ctx.dateStr} ${ctx.timeStr}',
    if (_has(ctx.orderNotes)) '*** NOTE: ${ctx.orderNotes!.trim()} ***',
  ].where((l) => l.isNotEmpty).toList();

  final footerLines = <String>[
    if (_has(ctx.waiterName)) 'Steward: ${ctx.waiterName}',
    if (_has(ctx.operatorName)) 'Operator: ${ctx.operatorName}',
  ];

  List<String> safe(List<String> lines) =>
      lines.map(toPrinterSafeText).toList(growable: false);
  return EscposDoc(
    title: toPrinterSafeText(ctx.stationLabel),
    subtitleLines: safe(subtitleLines),
    itemLines: safe(<String>[for (final it in ctx.items) ..._itemLines(it)]),
    footerLines: safe(footerLines),
  );
}

/// One copy of [doc] as the desk's `buildDoc` lays it out.
String _buildDoc(EscposDoc doc) {
  final out = StringBuffer(_init);
  out
    ..write(_alignCenter)
    ..write(_sizeDouble)
    ..write(_boldOn)
    ..write('${doc.title}\n')
    ..write(_sizeNormal)
    ..write(_boldOff);
  for (final line in doc.subtitleLines) {
    out.write('$line\n');
  }
  out
    ..write(_rule)
    ..write(_alignLeft);
  for (final line in doc.itemLines) {
    out.write('$line\n');
  }
  if (doc.footerLines.isNotEmpty) {
    out.write(_rule);
    for (final line in doc.footerLines) {
      out.write('$line\n');
    }
  }
  out
    ..write(_feed3)
    ..write(_cutPartial);
  return out.toString();
}

/// The bytes the desk's `sendNetworkPrint` writes: [copies] whole tickets
/// (`copies <= 0` counts as 1), latin1.
List<int> escposBytes(EscposDoc doc, {int copies = 1}) {
  final single = _buildDoc(doc);
  final n = copies > 0 ? copies : 1;
  return latin1.encode(List<String>.filled(n, single).join());
}

